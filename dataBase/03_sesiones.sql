--  Script 03 · SESIONES Y REFRESH TOKENS
--  Uso: psql -d sgp_tulua -f 03_sesiones.sql
--
--  Crea la tabla `sesiones`, que soporta:
--    - refresh tokens con rotación;
--    - detección de reutilización del refresh anterior;
--    - invalidación persistente de logout (revocada_en).
--
--  No modifica tablas existentes. Es idempotente.
-- ============================================================================

\set ON_ERROR_STOP on
SET client_encoding = 'UTF8';

BEGIN;

CREATE TABLE IF NOT EXISTS sesiones (
  id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id                  BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  refresh_token_hash          VARCHAR(255) NOT NULL,
  refresh_token_anterior_hash VARCHAR(255),
  refresh_expira_en           TIMESTAMPTZ NOT NULL,
  revocada_en                 TIMESTAMPTZ,
  creada_en                   TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sesiones_refresh_token_hash_key UNIQUE (refresh_token_hash)
);

CREATE INDEX IF NOT EXISTS idx_sesiones_usuario
  ON sesiones (usuario_id, revocada_en);

CREATE INDEX IF NOT EXISTS idx_sesiones_anterior
  ON sesiones (refresh_token_anterior_hash);

DROP TRIGGER IF EXISTS trg_sesiones_marca ON sesiones;
CREATE TRIGGER trg_sesiones_marca
BEFORE UPDATE ON sesiones
FOR EACH ROW
EXECUTE FUNCTION fn_marca_actualizacion();

COMMENT ON TABLE sesiones IS
  'Sesiones autenticadas: hash del refresh token, rotación y revocación persistente de logout.';
COMMENT ON COLUMN sesiones.refresh_token_hash IS
  'SHA-256 del refresh token vigente; nunca se guarda el token en claro.';
COMMENT ON COLUMN sesiones.refresh_token_anterior_hash IS
  'Hash anterior para detectar reutilización de un refresh ya rotado.';
COMMENT ON COLUMN sesiones.revocada_en IS
  'Fecha de logout o revocación; NULL si la sesión sigue activa.';

COMMIT;

\echo '=== SESIONES CREADAS: tabla sesiones, 4 índices y trigger de actualización ==='
